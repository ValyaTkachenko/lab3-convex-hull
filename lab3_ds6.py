def read_dataset(filename):
    points = []
    with open(filename) as f:
        for line in f:
            parts = line.split()
            if len(parts) == 2:
                x = int(parts[0])
                y = int(parts[1])
                points.append((x, y))
    return points

points = read_dataset("DS6.txt")
print("Кількість точок:", len(points))

"""## Крок 2. Пошук опуклої оболонки"""

def cross(o, a, b):
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

def convex_hull(points):
    points = sorted(set(points))

    lower = []
    for p in points:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)

    upper = []
    for p in reversed(points):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)

    return lower[:-1] + upper[:-1]

hull = convex_hull(points)
print("Кількість вершин опуклої оболонки:", len(hull))
print(hull)

"""## Крок 3. Збереження опуклої оболонки у файл"""

def save_dataset(filename, points):
    with open(filename, "w") as f:
        for x, y in points:
            f.write(f"{x} {y}\n")

save_dataset("hull_DS6.txt", hull)
print("Опуклу оболонку збережено у файл hull_DS6.txt")

"""## Крок 4. Відображення опуклої оболонки"""

from PIL import Image, ImageDraw

WIDTH = 960
HEIGHT = 540

def to_canvas(x, y):
    return x, HEIGHT - 1 - y

def draw_hull(draw, hull):
    for i in range(len(hull)):
        p1 = to_canvas(*hull[i])
        p2 = to_canvas(*hull[(i + 1) % len(hull)])
        draw.line([p1, p2], fill="blue", width=2)

image_hull = Image.new("RGB", (WIDTH, HEIGHT), "white")
draw = ImageDraw.Draw(image_hull)
draw_hull(draw, hull)

image_hull.save("hull_DS6.png")
image_hull

"""## Крок 5. Відображення точок разом з опуклою оболонкою"""

image_result = Image.new("RGB", (WIDTH, HEIGHT), "white")
draw = ImageDraw.Draw(image_result)

for x, y in points:
    draw.point(to_canvas(x, y), fill="black")

draw_hull(draw, hull)

image_result.save("result_DS6.png")
image_result

